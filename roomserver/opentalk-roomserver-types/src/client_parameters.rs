use opentalk_types_common::{
    roomserver::DeviceSecret,
    time::TimeZone,
    users::{UserId, UserInfo},
    utils::ExampleData,
};
use opentalk_types_signaling::{ParticipationVisibility, Role};
use serde::{Deserialize, Deserializer, Serialize, Serializer};

use crate::{public_user_profile::PublicUserProfile, room_kind::RoomKind};

/// Client context required for a signaling connection
#[derive(Debug, Clone, PartialEq, Eq)]
#[cfg_attr(feature = "utoipa", derive(utoipa::ToSchema), schema(example = json!(ClientParameters::example_data())))]
pub struct ClientParameters {
    /// Identifier to maintain participant state across reconnections, is generated by the client
    device_secret: DeviceSecret,

    /// Information about a registered user
    #[cfg_attr(feature = "utoipa", serde(flatten))]
    kind: ClientKind,

    /// The role that the client assumes in the meeting.
    role: Role,
}

impl ClientParameters {
    pub fn call_in(device_secret: DeviceSecret) -> Self {
        Self::with_fixed_role(device_secret, ClientKind::CallIn)
    }

    pub fn recorder(device_secret: DeviceSecret, room: RoomKind) -> Self {
        Self::with_fixed_role(device_secret, ClientKind::Recorder { room })
    }

    pub fn transcription(device_secret: DeviceSecret, room: RoomKind) -> Self {
        Self::with_fixed_role(device_secret, ClientKind::Transcription { room })
    }

    pub fn unregistered(device_secret: DeviceSecret) -> Self {
        Self::with_fixed_role(device_secret, ClientKind::Unregistered)
    }

    pub fn registered(device_secret: DeviceSecret, profile: PublicUserProfile, role: Role) -> Self {
        Self {
            device_secret,
            kind: ClientKind::Registered { profile },
            role,
        }
    }

    pub fn device_secret(&self) -> &DeviceSecret {
        &self.device_secret
    }

    pub fn kind(&self) -> &ClientKind {
        &self.kind
    }

    pub fn role(&self) -> Role {
        self.role
    }

    fn with_fixed_role(device_secret: DeviceSecret, kind: ClientKind) -> Self {
        // Every kind built here has a fixed role; registered clients use `registered` instead.
        let role = kind.fixed_role();
        debug_assert!(
            role.is_some(),
            "with_fixed_role called with a kind that has no fixed role"
        );
        Self {
            device_secret,
            kind,
            role: role.unwrap_or(Role::Guest),
        }
    }

    fn has_valid_role(&self) -> bool {
        self.kind
            .fixed_role()
            .is_none_or(|expected_role| self.role == expected_role)
    }
}

impl Serialize for ClientParameters {
    fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>
    where
        S: Serializer,
    {
        if !self.has_valid_role() {
            return Err(<S::Error as serde::ser::Error>::custom(
                "role does not match client kind",
            ));
        }

        #[derive(Serialize)]
        struct ClientParametersRef<'a> {
            device_secret: &'a DeviceSecret,
            #[serde(flatten)]
            kind: &'a ClientKind,
            role: Role,
        }

        ClientParametersRef {
            device_secret: &self.device_secret,
            kind: &self.kind,
            role: self.role,
        }
        .serialize(serializer)
    }
}

impl<'de> Deserialize<'de> for ClientParameters {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: Deserializer<'de>,
    {
        #[derive(Deserialize)]
        struct ClientParametersOwned {
            device_secret: DeviceSecret,
            #[serde(flatten)]
            kind: ClientKind,
            role: Role,
        }

        let parameters = ClientParametersOwned::deserialize(deserializer)?;
        let parameters = Self {
            device_secret: parameters.device_secret,
            kind: parameters.kind,
            role: parameters.role,
        };

        if !parameters.has_valid_role() {
            return Err(<D::Error as serde::de::Error>::custom(
                "role does not match client kind",
            ));
        }

        Ok(parameters)
    }
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[cfg_attr(feature = "utoipa", derive(utoipa::ToSchema))]
#[serde(rename_all = "snake_case", tag = "kind")]
pub enum ClientKind {
    /// A registered user
    Registered { profile: PublicUserProfile },

    /// A pseudonymous user without a registered account
    Unregistered,

    /// Invisible recording participant
    Recorder {
        /// Room for which the recording was requested from
        ///
        /// Recorders may only access the recording-service commands & events in this room
        room: RoomKind,
    },

    /// Invisible service participant used by the transcription service
    Transcription {
        /// Room for which the transcription was requested from
        room: RoomKind,
    },

    /// Telephone call-In participant which identifies via a meeting id & pin
    CallIn,
}

impl ClientKind {
    fn fixed_role(&self) -> Option<Role> {
        match self {
            ClientKind::Registered { .. } => None,
            ClientKind::Unregistered | ClientKind::CallIn => Some(Role::Guest),
            ClientKind::Recorder { .. } | ClientKind::Transcription { .. } => Some(Role::User),
        }
    }

    pub fn user_id(&self) -> Option<UserId> {
        match self {
            ClientKind::Registered { profile } => Some(profile.id),
            ClientKind::Unregistered
            | ClientKind::Recorder { .. }
            | ClientKind::CallIn
            | ClientKind::Transcription { .. } => None,
        }
    }

    pub fn email(&self) -> Option<&str> {
        match self {
            ClientKind::Registered { profile } => Some(&profile.email),
            ClientKind::Unregistered
            | ClientKind::Recorder { .. }
            | ClientKind::CallIn
            | ClientKind::Transcription { .. } => None,
        }
    }

    pub fn avatar_url(&self) -> Option<&str> {
        match self {
            ClientKind::Registered { profile } => Some(&profile.user_info.avatar_url),
            ClientKind::CallIn
            | ClientKind::Unregistered
            | ClientKind::Recorder { .. }
            | ClientKind::Transcription { .. } => None,
        }
    }

    pub fn user_info(&self) -> Option<&UserInfo> {
        match self {
            ClientKind::Registered { profile } => Some(&profile.user_info),
            ClientKind::CallIn
            | ClientKind::Unregistered
            | ClientKind::Recorder { .. }
            | ClientKind::Transcription { .. } => None,
        }
    }

    pub fn participant_kind(&self) -> ParticipationKind {
        match &self {
            ClientKind::Registered { .. } => ParticipationKind::Registered,
            ClientKind::Unregistered => ParticipationKind::Unregistered,
            ClientKind::Recorder { .. } => ParticipationKind::Recorder,
            ClientKind::Transcription { .. } => ParticipationKind::Transcription,
            ClientKind::CallIn => ParticipationKind::CallIn,
        }
    }

    /// Returns `true` if the participant is a service, `false` otherwise.
    ///
    /// Returns `false` for call-in users because they're users even tough they're proxied through a
    /// service.
    pub fn is_service(&self) -> bool {
        self.participant_kind().is_service()
    }

    pub fn is_service_or_callin(&self) -> bool {
        self.participant_kind().is_service_or_callin()
    }

    /// Returns `true` if the participant is a call-in user, otherwise return `false`.
    pub fn is_call_in(&self) -> bool {
        match self {
            ClientKind::Registered { .. }
            | ClientKind::Unregistered
            | ClientKind::Recorder { .. }
            | ClientKind::Transcription { .. } => false,
            ClientKind::CallIn => true,
        }
    }

    pub fn time_zone(&self) -> Option<TimeZone> {
        match self {
            ClientKind::Registered { profile } => Some(profile.timezone),
            ClientKind::Recorder { .. }
            | ClientKind::CallIn
            | ClientKind::Unregistered
            | ClientKind::Transcription { .. } => None,
        }
    }

    /// Returns `true` if the client kind is [`Registered`].
    ///
    /// [`Registered`]: ClientKind::Registered
    #[must_use]
    pub fn is_registered(&self) -> bool {
        matches!(self, Self::Registered { .. })
    }
}

impl ClientKind {
    pub fn visibility(&self) -> ParticipationVisibility {
        match self {
            ClientKind::Registered { .. } | ClientKind::Unregistered | ClientKind::CallIn => {
                ParticipationVisibility::Visible
            }
            ClientKind::Recorder { .. } | ClientKind::Transcription { .. } => {
                ParticipationVisibility::Hidden
            }
        }
    }
}

impl ExampleData for ClientParameters {
    fn example_data() -> Self {
        Self::registered(
            DeviceSecret::example_data(),
            PublicUserProfile::example_data(),
            Role::Moderator,
        )
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize, Hash)]
#[serde(rename_all = "snake_case")]
pub enum ParticipationKind {
    Registered,
    Unregistered,
    Recorder,
    Transcription,
    CallIn,
}

impl ParticipationKind {
    /// Returns `true` if the participant is a service, `false` otherwise.
    ///
    /// Returns `false` for call-in users because they're users even tough they're proxied through a
    /// service.
    pub fn is_service(&self) -> bool {
        match self {
            ParticipationKind::Registered
            | ParticipationKind::Unregistered
            | ParticipationKind::CallIn => false,
            ParticipationKind::Recorder | ParticipationKind::Transcription => true,
        }
    }

    /// Returns `true` if the participant is a service or call-in user, otherwise return `false`.
    pub fn is_service_or_callin(&self) -> bool {
        match self {
            ParticipationKind::Registered | ParticipationKind::Unregistered => false,
            ParticipationKind::Recorder
            | ParticipationKind::Transcription
            | ParticipationKind::CallIn => true,
        }
    }
}

impl From<&ClientKind> for ParticipationKind {
    fn from(value: &ClientKind) -> Self {
        match value {
            ClientKind::Registered { .. } => Self::Registered,
            ClientKind::Unregistered => Self::Unregistered,
            ClientKind::Recorder { .. } => Self::Recorder,
            ClientKind::Transcription { .. } => Self::Transcription,
            ClientKind::CallIn => Self::CallIn,
        }
    }
}

#[cfg(test)]
mod tests {
    use opentalk_types_common::{roomserver::DeviceSecret, utils::ExampleData};
    use opentalk_types_signaling::Role;
    use pretty_assertions::assert_eq;
    use serde_json::json;

    use crate::{
        client_parameters::{ClientKind, ClientParameters, ParticipationKind},
        public_user_profile::PublicUserProfile,
        room_kind::RoomKind,
    };

    #[test]
    fn guest() {
        let client_parameter = ClientParameters::unregistered(DeviceSecret::example_data());
        assert_eq!(
            client_parameter.kind().participant_kind(),
            ParticipationKind::Unregistered
        );

        let value = serde_json::to_value(client_parameter).unwrap();

        assert_eq!(
            value,
            json!(
                {
                    "role": "guest",
                    "device_secret": "v3rys3cr3tD3v1ce5tr1ng",
                    "kind": "unregistered",
                }
            )
        );
    }

    #[test]
    fn registered() {
        let client_parameter = ClientParameters::registered(
            DeviceSecret::example_data(),
            PublicUserProfile::example_data(),
            Role::User,
        );
        assert_eq!(
            client_parameter.kind().participant_kind(),
            ParticipationKind::Registered
        );

        let value = serde_json::to_value(client_parameter).unwrap();

        assert_eq!(
            value,
            json!(
                {
                    "device_secret": "v3rys3cr3tD3v1ce5tr1ng",
                    "kind": "registered",
                    "role": "user",
                    "profile": {
                        "avatar_url": "https://gravatar.com/avatar/c160f8cc69a4f0bf2b0362752353d060",
                        "display_name": "Alice Adams",
                        "email": "alice@example.com",
                        "firstname": "Alice",
                        "lastname": "Adams",
                        "id": "00000000-0000-0000-0000-0000000a11c3",
                        "title": "",
                        "timezone": "Europe/Berlin",
                    }
                }
            )
        )
    }

    #[test]
    fn service() {
        let client_parameter =
            ClientParameters::recorder(DeviceSecret::example_data(), RoomKind::Main);
        assert_eq!(
            client_parameter.kind().participant_kind(),
            ParticipationKind::Recorder
        );

        let value = serde_json::to_value(client_parameter).unwrap();

        assert_eq!(
            value,
            json!({
                "role": "user",
                "device_secret": "v3rys3cr3tD3v1ce5tr1ng",
                "kind": "recorder",
                "room": {
                    "kind": "main",
                }
            })
        );
    }

    #[test]
    fn call_in() {
        let client_parameter = ClientParameters::call_in(DeviceSecret::example_data());
        assert_eq!(
            client_parameter.kind().participant_kind(),
            ParticipationKind::CallIn
        );

        let value = serde_json::to_value(client_parameter).unwrap();

        assert_eq!(
            value,
            json!({
                "role": "guest",
                "device_secret": "v3rys3cr3tD3v1ce5tr1ng",
                "kind": "call_in",
            })
        );
    }

    #[test]
    fn is_call_in_affects_all_call_in_kinds() {
        let call_in = ClientKind::CallIn;
        assert!(call_in.is_call_in());
    }

    #[test]
    fn serde_rejects_roles_that_do_not_match_client_kind() {
        let invalid = ClientParameters {
            device_secret: DeviceSecret::example_data(),
            kind: ClientKind::CallIn,
            role: Role::User,
        };
        assert!(serde_json::to_value(invalid).is_err());

        let invalid = json!({
            "device_secret": "v3rys3cr3tD3v1ce5tr1ng",
            "kind": "unregistered",
            "role": "user",
        });
        assert!(serde_json::from_value::<ClientParameters>(invalid).is_err());

        let invalid = json!({
            "device_secret": "v3rys3cr3tD3v1ce5tr1ng",
            "kind": "recorder",
            "room": { "kind": "main" },
            "role": "guest",
        });
        assert!(serde_json::from_value::<ClientParameters>(invalid).is_err());
    }
}
